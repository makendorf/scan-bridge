namespace ScanBridge.Models;

/// <summary>
/// Конфигурация параметров переподключения при потере связи с COM-портом.
/// Определяет задержку, количество попыток и режим работы.
/// </summary>
public class ReconnectConfig
{
    /// <summary>
    /// Задержка между попытками переподключения в миллисекундах (минимум 100).
    /// Увеличивается экспоненциально при каждой неудачной попытке.
    /// </summary>
    public int DelayMs { get; set; } = 1000;

    /// <summary>
    /// Максимальное количество попыток переподключения.
    /// При достижении лимита сканер останавливается (если не в режиме Continuous).
    /// </summary>
    public int MaxRetries { get; set; } = 10;

    /// <summary>
    /// Режим непрерывного переподключения. Если true, сканер будет пытаться
    /// переподключаться бесконечно, игнорируя лимит MaxRetries.
    /// </summary>
    public bool Continuous { get; set; }
}
